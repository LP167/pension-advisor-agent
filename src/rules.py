_COMPILED = [(r, [re.compile(p) for p in r["위반"]],
              re.compile(r["필수문맥"]) if r.get("필수문맥") else None,
              re.compile(r["제외문맥"]) if r.get("제외문맥") else None) for r in RULES]

# 틀린 전제를 '바로잡는' 문장은 위반이 아니다.
# 전제교정은 과제 평가지표('정확성 — 잘못된 전제를 바로잡는가')가 요구하는 행동이라
# 여기서 잡으면 잘한 답변을 깎게 된다.
NEGATION = re.compile(
    r"아닙니다|아니라|아니고|아니며|않습니다|않으며|않고|않는|없습니다"
    r"|어렵습니다|잘못|오해|착각|와는\s*달리|과는\s*달리|말씀처럼|생각과\s*달리|주의")

# 문장 분리는 마침표 뒤 '공백'을 요구한다. 그러지 않으면 "16.5%"·"5.5%" 의 소수점에서
# 문장이 쪼개져 규칙 문맥과 부정문 가드가 전부 무력화된다(실측으로 확인).
_SENT_SPLIT = re.compile(r"(?<=[.!?])\s+|\n+")


def check_contradictions(answer: str) -> List[Dict[str, Any]]:
    """답변에서 정본 규칙과 관계가 뒤집힌 진술을 찾는다.
    판정은 문장 단위로 한다 — 답변 전체에서 정규식을 돌리면 앞뒤 문장의 부정을 놓친다."""
    a = answer or ""
    out = []
    for rule, pats, need, avoid in _COMPILED:
        found = None
        for sent in _SENT_SPLIT.split(a):
            if need and not need.search(sent):      continue
            if avoid and avoid.search(sent):        continue
            if NEGATION.search(sent):               continue   # 전제교정 문장
            if any(p.search(sent) for p in pats):
                found = sent
                break
        if found:
            out.append({"rule": rule["id"], "정본": rule["정본"], "근거": rule["근거"],
                        "위반문구": re.sub(r"\s+", " ", found).strip()[:150]})
    return out
